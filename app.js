        function populateSelectOptions() {
            const diseaseSelect = document.getElementById('diseaseFilter');
            const medicineSelect = document.getElementById('medicineFilter');
            const foodSelect = document.getElementById('foodFilter');
            const procedureSelect = document.getElementById('procedureFilter');
            const preventionSelect = document.getElementById('preventionFilter');

            const diseasesSet = new Set();
            const medicinesSet = new Set();
            const foodsSet = new Set();
            const proceduresSet = new Set();
            const preventionsSet = new Set();

            allCards.forEach(card => {
                if (card.diseases_and_symptoms) {
                    card.diseases_and_symptoms.forEach(d => diseasesSet.add(d));
                }
                if (card.usage_types) {
                    if (card.usage_types.includes('دواء_واستشفاء_صريح')) medicinesSet.add(card.title);
                    if (card.usage_types.includes('غذاء_وعادة')) foodsSet.add(card.title);
                    if (card.usage_types.includes('إجراء_جراحي_يدوي')) proceduresSet.add(card.title);
                    if (card.usage_types.includes('وقاية_وحفظ_صحة') || card.usage_types.includes('نظافة_وسنن_فطرة')) preventionsSet.add(card.title);
                }
            });

            const fillSelect = (selectElem, itemsSet) => {
                selectElem.innerHTML = '<option value="all">' + selectElem.options[0].text + '</option>';
                Array.from(itemsSet).sort().forEach(item => {
                    const opt = document.createElement('option');
                    opt.value = item;
                    opt.textContent = item;
                    selectElem.appendChild(opt);
                });
            };

            fillSelect(diseaseSelect, diseasesSet);
            fillSelect(medicineSelect, medicinesSet);
            fillSelect(foodSelect, foodsSet);
            fillSelect(procedureSelect, proceduresSet);
            fillSelect(preventionSelect, preventionsSet);
        }

